#!/usr/bin/env python3
"""Canopy Bundler: Packages src/ modules into the Horizon native mixin bundle."""
from pathlib import Path
import re

ROOT = Path(__file__).parent
SRC = ROOT / "src"
OUT = ROOT / "mixins" / "canopy" / "canopy.rs"

def clean(code):
    # Strip inner doc comments (//! is banned by horizon-mixins)
    lines = [l for l in code.splitlines() if not l.strip().startswith("//!")]
    text = "\n".join(lines)
    # Rewrite crate:: imports to super:: so they work inside pub mod
    text = re.sub(r"\bcrate::style\b", "super::style", text)
    text = re.sub(r"\bcrate::layout\b", "super::layout", text)
    text = re.sub(r"\bcrate::event\b", "super::event", text)
    text = re.sub(r"\bcrate::node\b", "super::node", text)
    text = re.sub(r"\bcrate::Component\b", "super::Component", text)
    text = re.sub(r"\bcrate::Dimension\b", "super::style::Dimension", text)
    return text

modules = [
    ("style", SRC / "style.rs"),
    ("layout", SRC / "layout.rs"),
    ("event", SRC / "event.rs"),
    ("node", SRC / "node.rs"),
    ("widgets", SRC / "widgets.rs"),
]

bundle = ["// Generated by bundle.py — DO NOT EDIT MANUALLY\n"]
for name, path in modules:
    content = clean(path.read_text())
    bundle.append(f"#[allow(unused_imports, dead_code)]\npub mod {name} {{\n{content}\n}}\n")

bundle.append("""#[allow(unused_imports)]
pub use event::*;
#[allow(unused_imports)]
pub use layout::*;
#[allow(unused_imports)]
pub use node::*;
#[allow(unused_imports)]
pub use style::*;
#[allow(unused_imports)]
pub use widgets::*;

#[macro_export]
macro_rules! children {
    ($($c:expr),* $(,)?) => {
        vec![$(Box::new($c) as Box<dyn Component>),*]
    };
}
#[allow(unused_imports)]
pub use crate::children;
""")
OUT.write_text("\n".join(bundle))
print("Canopy mixin bundled successfully!")